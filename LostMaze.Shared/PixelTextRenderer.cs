    public Vector2 MeasureText(string text, int scale, int spacing = 1, int lineSpacing = 3)
    {
        var lines = text.Replace("\r", string.Empty).Split('\n');
        var maxWidth = 0f;

        foreach (var rawLine in lines)
        {
            var width = 0f;
            var line = rawLine.ToUpperInvariant();

            for (var i = 0; i < line.Length; i++)
            {
                var glyph = Glyphs.ContainsKey(line[i]) ? line[i] : '?';
                width += (Glyphs[glyph][0].Length * scale) + spacing;
            }

            if (width > 0)
            {
                width -= spacing;
            }

            maxWidth = MathF.Max(maxWidth, width);
        }

        var totalHeight = (lines.Length * 7 * scale) + ((lines.Length - 1) * lineSpacing);
        return new Vector2(maxWidth, totalHeight);
    }

    public void DrawString(
        SpriteBatch spriteBatch,
        Texture2D pixel,
        string text,
        Vector2 position,
        Color color,
        int scale,
        int spacing = 1,
        int lineSpacing = 3)
    {
        var linePosition = position;
        var lines = text.Replace("\r", string.Empty).Split('\n');

        foreach (var rawLine in lines)
        {
            var x = linePosition.X;
            var line = rawLine.ToUpperInvariant();

            foreach (var letter in line)
            {
                var glyphKey = Glyphs.ContainsKey(letter) ? letter : '?';
                var glyph = Glyphs[glyphKey];

                for (var row = 0; row < glyph.Length; row++)
                {
                    for (var column = 0; column < glyph[row].Length; column++)
                    {
                        if (glyph[row][column] != '#')
                        {
                            continue;
                        }

                        spriteBatch.Draw(
                            pixel,
                            new Rectangle((int)x + (column * scale), (int)linePosition.Y + (row * scale), scale, scale),
                            color);
                    }
                }

                x += (glyph[0].Length * scale) + spacing;
            }

            linePosition = new Vector2(position.X, linePosition.Y + (7 * scale) + lineSpacing);
        }
    }
